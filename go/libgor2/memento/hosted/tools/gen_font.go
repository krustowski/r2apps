//go:build ignore

// Generates the hosted canvas font from the r2 backend's checked-in table.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strconv"
)

func main() {
	if len(os.Args) != 2 {
		panic("usage: go run tools/gen_font.go /path/to/R2_TerminusFont.h")
	}
	font, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	number := func(pattern string) int {
		match := regexp.MustCompile(pattern).FindSubmatch(font)
		if len(match) != 2 {
			panic("missing font dimensions")
		}
		n, err := strconv.Atoi(string(match[1]))
		if err != nil {
			panic(err)
		}
		return n
	}
	width := number(`r2_font_char_width\s*=\s*(\d+)`)
	height := number(`r2_font_char_height\s*=\s*(\d+)`)
	start := bytes.Index(font, []byte("r2_terminus_glyphs"))
	if start < 0 {
		panic("missing glyph table")
	}
	glyphs := regexp.MustCompile(`0x[0-9a-fA-F]{2}`).FindAll(font[start:], -1)
	if width > 8 || len(glyphs) != 256*height {
		panic("unexpected font layout")
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by tools/gen_font.go from Memento's R2_TerminusFont.h; DO NOT EDIT.\n\npackage hosted\n\n")
	fmt.Fprintf(&out, "const (FontWidth = %d; FontHeight = %d)\n\nvar glyphs = [256 * FontHeight]byte{\n", width, height)
	for i, glyph := range glyphs {
		fmt.Fprintf(&out, "%s,", glyph)
		if (i+1)%height == 0 {
			out.WriteByte('\n')
		}
	}
	out.WriteString("}\n")
	source, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("font.go", source, 0644); err != nil {
		panic(err)
	}
}
